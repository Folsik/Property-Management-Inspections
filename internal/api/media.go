import (
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net/http"
	"net/url"
	"os"
	"strings"
	"time"
)

func hmacSHA(key []byte, msg string) []byte {
	m := hmac.New(sha256.New, key)
	_, _ = m.Write([]byte(msg))
	return m.Sum(nil)
}
func hexHash(s string) string { h := sha256.Sum256([]byte(s)); return hex.EncodeToString(h[:]) }

// sigV4Signature centralizes AWS4 signing key derivation across S3 operations.
// The caller remains responsible for canonical URI, headers and query ordering.
func sigV4Signature(secret, region, date, timestamp, scope, canonical string) string {
	toSign := "AWS4-HMAC-SHA256\n" + timestamp + "\n" + scope + "\n" + hexHash(canonical)
	key := hmacSHA([]byte("AWS4"+secret), date)
	key = hmacSHA(key, region)
	key = hmacSHA(key, "s3")
	key = hmacSHA(key, "aws4_request")
	return hex.EncodeToString(hmacSHA(key, toSign))
}

func presignPUT(endpoint, bucket, region, access, secret, objectKey, mime string, now time.Time) (string, error) {
	u, err := url.Parse(endpoint)
	if err != nil || u.Scheme != "https" || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || u.Path != "" {
		return "", fmt.Errorf("invalid storage endpoint")
	}
	if bucket == "" || strings.ContainsAny(bucket, "/ ") || region == "" || access == "" || secret == "" {
		return "", fmt.Errorf("incomplete storage configuration")
	}
	date := now.UTC().Format("20060102")
	amz := now.UTC().Format("20060102T150405Z")
	scope := date + "/" + region + "/s3/aws4_request"
	u.Path = "/" + bucket + "/" + objectKey
	u.RawPath = ""
	// All object keys are generated by this server and consist solely of safe characters.
	q := url.Values{}
	q.Set("X-Amz-Algorithm", "AWS4-HMAC-SHA256")
	q.Set("X-Amz-Credential", access+"/"+scope)
	q.Set("X-Amz-Date", amz)
	q.Set("X-Amz-Expires", "300")
	q.Set("X-Amz-SignedHeaders", "content-type;host")
	u.RawQuery = q.Encode()
	canonical := "PUT\n" + u.EscapedPath() + "\n" + u.RawQuery + "\ncontent-type:" + mime + "\nhost:" + u.Host + "\n\ncontent-type;host\nUNSIGNED-PAYLOAD"
	q.Set("X-Amz-Signature", sigV4Signature(secret, region, date, amz, scope, canonical))
	u.RawQuery = q.Encode()
	return u.String(), nil
}
func (s *Server) presignMedia(w http.ResponseWriter, r *http.Request) {
	if _, ok := s.role(r, "owner", "manager", "inspector"); !ok {
		fail(w, 403, "forbidden")
		return
	}
	inspection := r.PathValue("inspection")
	if !validID(inspection) {
		fail(w, 400, "invalid inspection ID")
		return
	}
	var in struct {
		MimeType  string `json:"mime_type"`
		SizeBytes int64  `json:"size_bytes"`
	}
	if !decode(w, r, &in) {
		return
	}
	switch in.MimeType {
	case "image/jpeg", "image/png", "image/heic", "audio/mp4", "audio/mpeg":
	default:
		fail(w, 400, "unsupported media type")
		return
	}
	if in.SizeBytes <= 0 || in.SizeBytes > 50<<20 {
		fail(w, 400, "media size out of range")
		return
	}
	endpoint, bucket, region, access, secret := os.Getenv("S3_ENDPOINT"), os.Getenv("S3_BUCKET"), os.Getenv("S3_REGION"), os.Getenv("S3_ACCESS_KEY_ID"), os.Getenv("S3_SECRET_ACCESS_KEY")
	if endpoint == "" || bucket == "" || region == "" || access == "" || secret == "" {
		fail(w, 503, "S3/R2 not configured")
		return
	}
	var present bool
	if err := s.db.QueryRow(r.Context(), "SELECT EXISTS(SELECT 1 FROM inspections WHERE organization_id=$1 AND id=$2)", r.PathValue("org"), inspection).Scan(&present); err != nil {
		fail(w, 503, "unavailable")
		return
	}
	if !present {
		fail(w, 404, "inspection not found")
		return
	}
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		fail(w, 500, "unavailable")
		return
	}
	objectKey := "organizations/" + r.PathValue("org") + "/inspections/" + inspection + "/" + hex.EncodeToString(b)
	link, err := presignPUT(endpoint, bucket, region, access, secret, objectKey, in.MimeType, time.Now())
	if err != nil {
		s.logger.Error("invalid media storage config", "error", err)
		fail(w, 503, "storage configuration invalid")
		return
	}
	var id string
	err = s.db.QueryRow(r.Context(), "INSERT INTO media_attachments(organization_id,inspection_id,uploaded_by,object_key,staging_key,mime_type,size_bytes) VALUES($1,$2,$3,$4,$4,$5,$6) RETURNING id", r.PathValue("org"), inspection, who(r).UserID, objectKey, in.MimeType, in.SizeBytes).Scan(&id)
	if err != nil {
		fail(w, 503, "unavailable")
		return
	}
	write(w, 201, map[string]any{"id": id, "upload_url": link, "method": "PUT", "headers": map[string]string{"Content-Type": in.MimeType}, "expires_in_seconds": 300, "state": "pending"})
}
